'use strict';
// Copies the app's real companion renderer into website/live/ so the page's
// companion is drawn and animated by the same code as the app, and writes
// live/renderer/frames.js: one resting snapshot per character plus its own
// activities (from src/main/companion.js). Run from dcapp/:
//   node website/tools/sync-live.js
const fs = require('fs');
const path = require('path');
const { Companion } = require('../../src/main/companion');
const characters = require('../../src/characters');

const SRC = path.join(__dirname, '..', '..', 'src');
const LIVE = path.join(__dirname, '..', 'live');
const copy = (from, to) => {
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.copyFileSync(from, to);
};

for (const f of ['renderer.js', 'ui.js', 'chirp.js', 'item.js']) copy(path.join(SRC, 'renderer', f), path.join(LIVE, 'renderer', f));
const ids = characters.list().map((c) => c.id);
for (const id of ids) for (const f of ['look.js', 'voice.js', 'lines.js']) copy(path.join(SRC, 'characters', id, f), path.join(LIVE, 'characters', id, f));

// The page itself: the app's index.html with the driver (live.js) in place of the main process.
let html = fs.readFileSync(path.join(SRC, 'renderer', 'index.html'), 'utf8');
html = html.replace(/<meta http-equiv="Content-Security-Policy"[^>]*>\s*/, '');
html = html.replace('<script src="renderer.js"></script>', '<script src="frames.js"></script>\n    <script src="live.js"></script>\n    <script src="renderer.js"></script>');
fs.writeFileSync(path.join(LIVE, 'renderer', 'live.html'), html);

const frames = {};
for (const c of characters.list()) {
  const comp = new Companion({ bounds: { left: 0, right: 1920, top: 0, floor: 1040 }, rng: () => 0.5, character: c });
  for (let i = 0; i < 300; i++) comp.update(1 / 60);
  comp.enter('idle', 10);
  const own = c.activities.filter((a) => !a.night && !a.fly && !a.move).map((a) => a.id);
  const durations = {};
  for (const id of own) {
    comp.startActivity(id);
    durations[id] = Math.min(9, Math.max(5, comp.stateDuration || 6));
    comp.enter('idle', 10);
  }
  frames[c.id] = { rest: { ...comp.snapshot(), events: [], cursor: { x: 0, y: -100 } }, own, durations };
}
fs.writeFileSync(path.join(LIVE, 'renderer', 'frames.js'), `// Generated by website/tools/sync-live.js from src/main/companion.js.\nwindow.FRAMES = ${JSON.stringify(frames)};\n`);
console.log('live companion synced:', ids.join(', '));
